// Prepares local assets: photo crops (WebP, two sizes), self-hosted fonts, and the
// subset of simple-icons used by the site. Run with `npm run assets`.
import sharp from 'sharp';
import fs from 'node:fs';
import path from 'node:path';
import * as si from 'simple-icons';

const root = path.resolve(import.meta.dirname, '..');
const SRC = process.env.PHOTO ?? path.resolve(root, '..', 'portfolio-assets', 'WhatsApp Image 2026-10-07 at 9.21.23 PM.jpeg');

// 1. Photo: portrait crop (4:5) centred on the subject, two widths.
const crop = { left: 168, top: 560, width: 832, height: 1040 };
for (const w of [480, 960]) {
  await sharp(SRC).extract(crop).resize(w).webp({ quality: 80 }).toFile(path.join(root, 'public/img', `saad-${w}.webp`));
}
// Square crop used for the OG card.
await sharp(SRC).extract({ left: 225, top: 600, width: 700, height: 700 }).resize(630).jpeg({ quality: 85 }).toFile(path.join(root, 'scripts', 'og-photo.jpg'));

// 2. Fonts: copy woff2 files from @fontsource into app/fonts for next/font/local.
const fonts = [
  ['poppins', ['600', '700']],
  ['inter', ['400', '600']],
];
for (const [fam, weights] of fonts) {
  for (const w of weights) {
    const f = `${fam}-latin-${w}-normal.woff2`;
    fs.copyFileSync(path.join(root, 'node_modules/@fontsource', fam, 'files', f), path.join(root, 'app/fonts', f));
  }
}

// 3. Icons: emit only what the site uses.
const ICONS = {
  html5: 'siHtml5', css: 'siCss', javascript: 'siJavascript', react: 'siReact', nextjs: 'siNextdotjs',
  tailwind: 'siTailwindcss', bootstrap: 'siBootstrap', gsap: 'siGreensock', node: 'siNodedotjs',
  python: 'siPython', webrtc: 'siWebrtc', supabase: 'siSupabase', postgresql: 'siPostgresql',
  pandas: 'siPandas', numpy: 'siNumpy', gemini: 'siGooglegemini', claude: 'siClaude', zapier: 'siZapier',
  meta: 'siMeta', electron: 'siElectron', vercel: 'siVercel', vite: 'siVite',
  github: 'siGithub', docker: 'siDocker',
};
const out = {};
for (const [k, name] of Object.entries(ICONS)) {
  const icon = si[name];
  if (!icon) throw new Error(`missing icon ${name}`);
  out[k] = { title: icon.title, path: icon.path, hex: icon.hex };
}
fs.writeFileSync(
  path.join(root, 'lib/icons.generated.ts'),
  `// Generated by scripts/build-assets.mjs from simple-icons (CC0). Do not edit.\n` +
  `export const ICONS = ${JSON.stringify(out, null, 1)} as const;\nexport type IconKey = keyof typeof ICONS;\n`,
);
console.log('assets ready');
